/**
 * Course index answers that cross IPC (main platform/courseIndex/).
 */

/** One course as a search result card needs it. */
export interface CourseIndexRow {
  id: string;
  name: string;
  /** Registrar code (Yanhe 2.0 `kcwybm`), or null. */
  number: string | null;
  /** Term key, `2026-2027-1`, or null. */
  term: string | null;
  teachers: string[];
}

export type CourseIndexSource = 'local' | 'online';

export type CourseIndexSearchResult =
  | {
    ok: true;
    source: CourseIndexSource;
    term: string;
    total: number;
    page: number;
    lastPage: number;
    courses: CourseIndexRow[];
  }
  | {
    ok: false;
    /**
     * local-missing: the course index on this computer does not hold the term;
     * online-failed: the AutoSlides Index refused or did not answer (`code` says which);
     * yanhekt: the current term is searched on Yanhekt (the caller's job).
     */
    reason: 'local-missing' | 'online-failed' | 'yanhekt';
    code?: string;
    message?: string;
  };

/** Settings → General → Search: what the course index on this computer holds. */
export interface CourseIndexStatus {
  /** False when this build carries no index key (the index is then off). */
  hasKey: boolean;
  /** Terms held, newest first, and the copy each is read from. */
  terms: Array<{ term: string; courses: number; sessions: number; source: 'downloaded' | 'bundled' }>;
  /** When the newest copy was generated by the indexer (ISO), or null. */
  generatedAt: string | null;
  /** Last check that reached the release (epoch ms), or null. */
  checkedAt: number | null;
  lastError: string | null;
  checking: boolean;
}
